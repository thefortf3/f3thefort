<?php
/**
 * Style preview: a frame around the site for trying the six alternative homepage styles live.
 *
 * Off unless wp-config.php says so, so production never shows it:
 *
 *   define( 'FORT_STYLE_PREVIEW', true );
 *
 * When on:
 *   - /style-preview/ is a page with a toolbar (style, page, width, side-by-side compare) around
 *     the real site in a frame (preview-frame.php);
 *   - the site loads assets/style-previews.css, whose rules apply only under
 *     html[data-fort-style="1".."6"];
 *   - an early script sets that attribute from the frame's name, ?fort_style=N, or the last choice
 *     (this browser only). Nothing is stored on the server.
 *
 * The CSS and JSON are generated by scripts/build-style-previews.mjs.
 *
 * @package Fort
 */

defined( 'ABSPATH' ) || exit;

function fort_style_preview_on() {
	return defined( 'FORT_STYLE_PREVIEW' ) && FORT_STYLE_PREVIEW;
}

/** The styles' names and summaries (assets/style-previews.json). */
function fort_style_preview_styles() {
	$file = get_template_directory() . '/assets/style-previews.json';
	$data = is_readable( $file ) ? json_decode( (string) file_get_contents( $file ), true ) : null; // phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents
	return is_array( $data['styles'] ?? null ) ? $data['styles'] : array();
}

if ( fort_style_preview_on() ) {
	add_action(
		'init',
		function () {
			add_rewrite_rule( '^style-preview/?$', 'index.php?fort_style_preview=1', 'top' );
			// A flush from somewhere that doesn't know about this setting (e.g. WP-CLI) drops the
			// address; put it back the next time the site loads.
			$rules = get_option( 'rewrite_rules' );
			if ( is_array( $rules ) && ! isset( $rules['^style-preview/?$'] ) ) {
				flush_rewrite_rules( false );
			}
		}
	);

	add_filter(
		'query_vars',
		function ( $vars ) {
			$vars[] = 'fort_style_preview';
			return $vars;
		}
	);

	add_action(
		'parse_query',
		function ( $q ) {
			if ( $q->is_main_query() && $q->get( 'fort_style_preview' ) ) {
				$q->is_home = false;
				$q->is_page = true;
			}
		}
	);

	add_filter(
		'template_include',
		function ( $template ) {
			if ( ! get_query_var( 'fort_style_preview' ) ) {
				return $template;
			}
			if ( ! defined( 'DONOTCACHEPAGE' ) ) {
				define( 'DONOTCACHEPAGE', true );
			}
			nocache_headers();
			header( 'X-Robots-Tag: noindex, nofollow' );
			return locate_template( 'preview-frame.php' ) ?: $template;
		}
	);

	// The alternative styles, after the theme's own stylesheet.
	add_action(
		'wp_enqueue_scripts',
		function () {
			wp_enqueue_style( 'fort-style-previews', get_template_directory_uri() . '/assets/style-previews.css', array( 'fort' ), (string) filemtime( get_template_directory() . '/assets/style-previews.css' ) );
		},
		20
	);

	// Before the page draws: pick the style from the frame's name (each frame keeps its own),
	// ?fort_style=N, or the last choice in this browser. 0 / nothing = the current look.
	add_action(
		'wp_head',
		function () {
			echo "<script>(function(){try{var d=document.documentElement,s=null,m=/^fortstyle:(\\d)\$/.exec(window.name||'');if(m){s=m[1];}else{var q=/[?&]fort_style=(\\d)/.exec(location.search);if(q){s=q[1];try{localStorage.setItem('fortStyle',s);}catch(e){}}else{try{s=localStorage.getItem('fortStyle');}catch(e){}}}if(s&&/^[1-6]\$/.test(s)){d.setAttribute('data-fort-style',s);}}catch(e){}})();</script>\n";
		},
		0
	);

	// A small way in from the site itself (not shown inside the frame).
	add_action(
		'wp_footer',
		function () {
			if ( get_query_var( 'fort_style_preview' ) ) {
				return;
			}
			printf(
				"<script>if(window.top===window.self){var a=document.createElement('a');a.href=%s;a.textContent='Compare styles \\u2197';a.setAttribute('style','position:fixed;left:12px;bottom:12px;z-index:99999;padding:8px 14px;background:#15171b;color:#f1efe8;border:1px solid #4a4e57;border-radius:999px;font:600 13px/1 system-ui,sans-serif;text-decoration:none;box-shadow:0 4px 16px rgba(0,0,0,.35)');document.body.appendChild(a);}</script>\n",
				wp_json_encode( home_url( '/style-preview/' ) )
			);
		}
	);
}
